//! Katakana for the system font.
//!
//! Covers the 46 basic katakana, the small ァィゥェォャュョッ, the long
//! vowel ー, the middle dot ・, ヴ, every voiced (゛) and semi-voiced (゜)
//! form, and 「」、。. Voiced forms are composed at draw time: the base
//! glyph with its top-right corner replaced by the mark, the way 8-bit
//! consoles did it. Glyphs are 7 columns wide in the 8×8 cell.

/// Which mark to compose onto a base glyph.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Mark {
    /// No mark.
    None,
    /// Dakuten ゛ (voiced).
    Dakuten,
    /// Handakuten ゜ (semi-voiced).
    Handakuten,
}

