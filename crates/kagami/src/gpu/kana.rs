/// Baked bitmaps, in the order of the art table (see [`lookup`]).
pub const GLYPHS: [[u8; 8]; ART.len()] = bake();

const fn bake() -> [[u8; 8]; ART.len()] {
    let mut out = [[0u8; 8]; ART.len()];
    let mut g = 0;
    while g < ART.len() {
        let bytes = ART[g].1.as_bytes();
        assert!(bytes.len() == 62, "kana art must be 7 rows of 8 columns");
        let mut row = 0;
        while row < 7 {
            let mut bits = 0u8;
            let mut col = 0;
            while col < 8 {
                let ch = bytes[row * 9 + col];
                assert!(
                    ch == b'#' || ch == b'.',
                    "kana art may only contain '#' and '.'"
                );
                if ch == b'#' {
                    bits |= 0x80 >> col;
                }
                col += 1;
            }
            if row < 6 {
                assert!(
                    bytes[row * 9 + 8] == b'|',
                    "kana rows must be separated by '|'"
                );
            }
            out[g][row] = bits;
            row += 1;
        }
        g += 1;
    }
    out
}

fn index_of(c: char) -> Option<usize> {
    ART.iter().position(|(k, _)| *k == c)
}

/// Resolves a character to a base glyph index and a mark, decomposing
/// voiced and semi-voiced katakana.
pub fn lookup(c: char) -> Option<(usize, Mark)> {
    if let Some(i) = index_of(c) {
        return Some((i, Mark::None));
    }
    let code = u32::from(c);
    let (base, mark) = match code {
        // カ..ヂ: voiced forms are base + 1.
        0x30AC..=0x30C2 if code % 2 == 0 => (code - 1, Mark::Dakuten),
        // ヅ, デ, ド and the ハ行 voiced forms バ, ビ, ブ, ベ, ボ: base + 1.
        0x30C5 | 0x30C7 | 0x30C9 | 0x30D0 | 0x30D3 | 0x30D6 | 0x30D9 | 0x30DC => {
            (code - 1, Mark::Dakuten)
        }
        // パ, ピ, プ, ペ, ポ: base + 2.
        0x30D1 | 0x30D4 | 0x30D7 | 0x30DA | 0x30DD => (code - 2, Mark::Handakuten),
        // ヴ
        0x30F4 => (0x30A6, Mark::Dakuten),
        // ヷヺ (rare): ワ゛ ヲ゛
        0x30F7 => (0x30EF, Mark::Dakuten),
        0x30FA => (0x30F2, Mark::Dakuten),
        _ => return None,
    };
    let base_char = char::from_u32(base)?;
    index_of(base_char).map(|i| (i, mark))
}

/// Returns the composed 8×8 bitmap for a katakana character, or `None` if
/// the character is not covered.
pub fn glyph(c: char) -> Option<[u8; 8]> {
    let (i, mark) = lookup(c)?;
    let mut g = GLYPHS[i];
    match mark {
        Mark::None => {}
        Mark::Dakuten => {
            g[0] = (g[0] & 0xF0) | 0b0000_1010;
            g[1] = (g[1] & 0xF0) | 0b0000_0101;
        }
        Mark::Handakuten => {
            g[0] = (g[0] & 0xF8) | 0b0000_0010;
            g[1] = (g[1] & 0xF8) | 0b0000_0101;
            g[2] = (g[2] & 0xF8) | 0b0000_0010;
        }
    }
    Some(g)
}

/// `true` for every character this module can draw.
pub fn covers(c: char) -> bool {
    lookup(c).is_some()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_basic_katakana_are_present() {
        const BASIC: &str = "アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン";
        for c in BASIC.chars() {
            assert!(index_of(c).is_some(), "{c} missing");
        }
        assert_eq!(BASIC.chars().count(), 46);
        for c in "ァィゥェォッャュョー・「」、。ヰヱヮヵヶ〜".chars() {
            assert!(covers(c), "{c}");
        }
    }

    #[test]
    fn voiced_forms_compose_from_bases() {
        const VOICED: &str = "ガギグゲゴザジズゼゾダヂヅデドバビブベボヴヷヺ";
        for c in VOICED.chars() {
            let (i, mark) = lookup(c).unwrap_or_else(|| panic!("{c}"));
            assert_eq!(mark, Mark::Dakuten, "{c}");
            let base = GLYPHS[i];
            let composed = glyph(c).unwrap();
            assert_ne!(base, composed);
            assert_eq!(&base[2..], &composed[2..], "{c}: only the top rows change");
        }
        for c in "パピプペポ".chars() {
            let (_, mark) = lookup(c).unwrap();
            assert_eq!(mark, Mark::Handakuten, "{c}");
            assert!(glyph(c).is_some());
        }
        assert_eq!(lookup('ガ').unwrap().0, index_of('カ').unwrap());
        assert_eq!(lookup('ポ').unwrap().0, index_of('ホ').unwrap());
        assert_eq!(lookup('ヴ').unwrap().0, index_of('ウ').unwrap());
    }

    #[test]
    fn uncovered_characters_return_none() {
        for c in ['a', 'あ', '漢', '\n', 'ヸ'] {
            assert!(glyph(c).is_none(), "{c}");
            assert!(!covers(c));
        }
    }

    #[test]
    fn glyphs_are_distinct_and_confined() {
        for (i, a) in GLYPHS.iter().enumerate() {
            assert_eq!(a[7], 0, "{}", ART[i].0);
            assert!(a.iter().any(|&r| r != 0), "{} is blank", ART[i].0);
            for (j, b) in GLYPHS.iter().enumerate().skip(i + 1) {
                assert_ne!(a, b, "{} and {} are identical", ART[i].0, ART[j].0);
            }
        }
    }
}
