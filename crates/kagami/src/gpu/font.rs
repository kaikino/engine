/// Bitmaps: one byte per row, MSB is the leftmost pixel.
pub const GLYPHS: [[u8; 8]; GLYPH_COUNT] = bake();

const fn bake() -> [[u8; 8]; GLYPH_COUNT] {
    let mut out = [[0u8; 8]; GLYPH_COUNT];
    let mut g = 0;
    while g < GLYPH_COUNT {
        let bytes = ART[g].as_bytes();
        assert!(bytes.len() == 41, "glyph art must be 7 rows of 5 columns");
        let mut row = 0;
        while row < 7 {
            let mut bits = 0u8;
            let mut col = 0;
            while col < 5 {
                let ch = bytes[row * 6 + col];
                assert!(
                    ch == b'#' || ch == b'.',
                    "glyph art may only contain '#' and '.'"
                );
                if ch == b'#' {
                    bits |= 0x80 >> col;
                }
                col += 1;
            }
            if row < 6 {
                assert!(
                    bytes[row * 6 + 5] == b'|',
                    "glyph rows must be separated by '|'"
                );
            }
            out[g][row] = bits;
            row += 1;
        }
        g += 1;
    }
    out
}

/// Returns the bitmap for any supported character: printable ASCII, katakana
/// (composing voiced marks), or the `?` glyph for anything else.
pub fn glyph_any(c: char) -> [u8; 8] {
    if c.is_ascii() {
        return *glyph(c);
    }
    super::kana::glyph(c).unwrap_or(*glyph('?'))
}

/// Returns the bitmap for a printable ASCII character, or the `?` glyph for
/// anything else. Use [`glyph_any`] to include katakana.
pub fn glyph(c: char) -> &'static [u8; 8] {
    let code = u32::from(c);
    let idx = if (u32::from(FIRST_CHAR)..u32::from(FIRST_CHAR) + GLYPH_COUNT as u32).contains(&code)
    {
        (code - u32::from(FIRST_CHAR)) as usize
    } else {
        (b'?' - FIRST_CHAR) as usize
    };
    &GLYPHS[idx]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_lookup() {
        assert_eq!(glyph(' '), &[0; 8]);
        assert_eq!(glyph('|')[0], 0b0010_0000);
        assert_eq!(glyph('_')[6], 0b1111_1000);
        assert_eq!(glyph('あ'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
        assert_eq!(glyph_any('A'), *glyph('A'));
        assert_eq!(glyph_any('あ'), *glyph('?'));
        assert_ne!(glyph_any('カ'), *glyph('?'));
        assert_eq!(glyph_any('カ'), super::super::kana::glyph('カ').unwrap());
        // Every glyph is confined to 5 columns and 7 rows.
        for g in &GLYPHS {
            assert_eq!(g[7], 0);
            for row in g {
                assert_eq!(row & 0b0000_0111, 0);
            }
        }
        // No two letters share a bitmap (a cheap typo check on the art).
        for (i, a) in GLYPHS.iter().enumerate() {
            for (j, b) in GLYPHS.iter().enumerate().skip(i + 1) {
                if a == b {
                    assert!(
                        i == 0 || j == 0,
                        "glyphs {} and {} are identical",
                        (i as u8 + FIRST_CHAR) as char,
                        (j as u8 + FIRST_CHAR) as char
                    );
                }
            }
        }
    }
}
